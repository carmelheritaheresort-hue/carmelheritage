async function migrate() {
  await db.exec('CREATE TABLE IF NOT EXISTS schema_migrations (id INTEGER PRIMARY KEY, name TEXT, applied_at TEXT)');
  await db.exec('ALTER TABLE schema_migrations ENABLE ROW LEVEL SECURITY');
  // Only one process may migrate at a time (e.g. two deployments building at once).
  await db.tx(async () => {
    await db.exec('SELECT pg_advisory_xact_lock(727001)');
    const done = new Set((await db.all('SELECT id FROM schema_migrations')).map(r => r.id));
    for (const m of migrations) {
      if (done.has(m.id)) continue;
      if (m.sql) await db.exec(m.sql);
      if (m.run) await m.run();
      await db.run('INSERT INTO schema_migrations(id,name,applied_at) VALUES (?,?,?)', m.id, m.name, new Date().toISOString());
      console.log(`Applied migration ${m.id}: ${m.name}`);
    }
    await seed();
  });
}

