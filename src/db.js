let pool = null;
function getPool() {
  if (pool) return pool;
  if (!config.databaseUrl) {
    throw new Error(config.isServerless
      ? 'DATABASE_URL is not set in Vercel. Add it under Project > Settings > Environment Variables (paste the contents of .env.vercel), then redeploy.'
      : 'DATABASE_URL is not set. Add the Supabase connection string to .env (see README).');
  }
  // Supabase requires TLS. Its certificate is not in Node's default store, so either supply the CA
  // (DATABASE_CA_CERT, from Supabase > Project Settings > Database > SSL) or accept the encrypted connection without CA pinning.
  const url = new URL(config.databaseUrl);
  url.searchParams.delete('sslmode');
  const local = ['localhost', '127.0.0.1'].includes(url.hostname);
  pool = new Pool({
    connectionString: url.toString(),
    ssl: local ? false : config.databaseCa ? { ca: config.databaseCa } : { rejectUnauthorized: false },
    max: config.isServerless ? 3 : 10,
    idleTimeoutMillis: 10000,
    connectionTimeoutMillis: 10000
  });
  pool.on('error', e => console.error('Database pool error:', e.message));
  return pool;
}

const als = new AsyncLocalStorage();

// Converts "?" placeholders (or @name with an object) to $1, $2 ... for pg.
function compile(sql, params) {
  if (params.length === 1 && params[0] && typeof params[0] === 'object' && !Array.isArray(params[0]) && !(params[0] instanceof Date) && !Buffer.isBuffer(params[0])) {
    const obj = params[0], names = [], values = [];
    const text = sql.replace(/@([a-z_][a-z0-9_]*)/gi, (m, name) => {
      if (!(name in obj)) throw new Error(`Missing SQL parameter @${name}`);
      let i = names.indexOf(name);
      if (i === -1) { names.push(name); values.push(obj[name]); i = names.length - 1; }
      return '$' + (i + 1);
    });
    return { text, values };
  }
  let n = 0;
  return { text: sql.replace(/\?/g, () => '$' + (++n)), values: params.map(v => (v === undefined ? null : v)) };
}

async function query(sql, params) {
  const { text, values } = compile(sql, params);
  const ctx = als.getStore();
  return (ctx ? ctx.client : getPool()).query(text, values);
}

const db = {
  async all(sql, ...params) { return (await query(sql, params)).rows; },
  async get(sql, ...params) { return (await query(sql, params)).rows[0]; },
  async run(sql, ...params) { const r = await query(sql, params); return { changes: r.rowCount, rows: r.rows }; },
  // INSERT ... and return the new row's id.
  async insert(sql, ...params) { return (await query(sql + ' RETURNING id', params)).rows[0].id; },
  async exec(sql) { const ctx = als.getStore(); return (ctx ? ctx.client : getPool()).query(sql); },
  // Runs fn inside a transaction. Code called from fn (any module) uses the same connection.
  // Nested calls become savepoints.
  async tx(fn) {
    const ctx = als.getStore();
    if (ctx) {
      const sp = `sp${++ctx.depth}`;
      await ctx.client.query(`SAVEPOINT ${sp}`);
      try { const r = await fn(); await ctx.client.query(`RELEASE SAVEPOINT ${sp}`); return r; }
      catch (e) { await ctx.client.query(`ROLLBACK TO SAVEPOINT ${sp}`); throw e; }
      finally { ctx.depth--; }
    }
    const client = await getPool().connect();
    try {
      await client.query('BEGIN');
      const r = await als.run({ client, depth: 0 }, fn);
      await client.query('COMMIT');
      return r;
    } catch (e) {
      try { await client.query('ROLLBACK'); } catch { /* connection already broken */ }
      throw e;
    } finally {
      client.release();
    }
  },
  async close() { if (pool) { await pool.end(); pool = null; } }
};

